const copyReferralBtn = document.getElementById("copyReferralBtn");
const refreshReferralBtn = document.getElementById("generateCodeBtn");

const shareWhatsappBtn = document.getElementById("shareWhatsappBtn");
const shareTelegramBtn = document.getElementById("shareTelegramBtn");
const shareNativeBtn = document.getElementById("shareNativeBtn");

const referralStatusBadge = document.getElementById("referralStatusBadge");
const referralInviteCount = document.getElementById("referralInviteCount");
const referralVerifiedCount = document.getElementById("referralVerifiedCount");
const referralRewardTotal = document.getElementById("referralRewardTotal");
const referralProgressBar = document.getElementById("referralProgressBar");
const referRewardRate = document.getElementById("referRewardRate");
