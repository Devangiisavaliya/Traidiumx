const affiliateAudience = document.getElementById("affiliateAudience");
const affiliatePlatform = document.getElementById("affiliatePlatform");
const affiliateFormMessage = document.getElementById("affiliateFormMessage");

let referralState = null;

function showMiniMessage(message, type = "success") {
    let messageBox = document.getElementById("referMiniMessage");

    if (!messageBox) {
        messageBox = document.createElement("div");
        messageBox.id = "referMiniMessage";
        document.body.appendChild(messageBox);
    }

    if (type === "error") {
        messageBox.className = "fixed bottom-6 right-6 z-[9999] max-w-sm rounded-2xl border border-red-400/30 bg-red-400/15 px-5 py-4 text-sm font-black text-red-300 shadow-2xl transition";
    } else {
        messageBox.className = "fixed bottom-6 right-6 z-[9999] max-w-sm rounded-2xl border border-emerald-400/30 bg-emerald-400/15 px-5 py-4 text-sm font-black text-emerald-300 shadow-2xl transition";
    }

    messageBox.textContent = message;
    messageBox.style.opacity = "1";
    messageBox.style.transform = "translateY(0)";

    window.setTimeout(() => {
        messageBox.style.opacity = "0";
        messageBox.style.transform = "translateY(12px)";
    }, 2800);
}

function formatUsdt(amount, decimals = 2) {
    const number = Number(amount || 0);
    return `${number.toLocaleString("en-US", {
        minimumFractionDigits: decimals,
        maximumFractionDigits: decimals
    })} USD`;
}

function sanitizeCode(value) {
    return String(value || "")
        .toUpperCase()
        .replace(/[^A-Z0-9]/g, "")
        .slice(0, 16);
}

function getBaseRegisterUrl() {
    return `${window.location.origin}/src/pages/register.html`;
}

function buildReferralLink(code) {
    const cleanCode = sanitizeCode(code);
    return `${getBaseRegisterUrl()}?ref=${encodeURIComponent(cleanCode)}`;
}

function setReferralInputs(code) {
    const cleanCode = sanitizeCode(code);

    if (referralCodeInput) {
        referralCodeInput.value = cleanCode || "LOGIN REQUIRED";
    }

    if (referralLinkInput) {
        referralLinkInput.value = cleanCode ? buildReferralLink(cleanCode) : "Login to get your referral link";
    }
}

function setLoginRequiredState() {
    referralState = null;
    setReferralInputs("");

    if (referralStatusBadge) {
        referralStatusBadge.textContent = "Login Required";
        referralStatusBadge.className = "rounded-full bg-yellow-400/10 px-3 py-1 text-xs font-black text-yellow-300";
    }

    if (referralInviteCount) referralInviteCount.textContent = "0";
    if (referralVerifiedCount) referralVerifiedCount.textContent = "0";
    if (referralRewardTotal) referralRewardTotal.textContent = formatUsdt(0);
    if (referralProgressBar) referralProgressBar.style.width = "0%";

    if (refreshReferralBtn) {
        refreshReferralBtn.textContent = "Login To Load Referral Code";
    }
}

function updateReferralUi(data) {
    const profile = data?.profile || {};
    const policy = data?.policy || {};

    referralState = data;

    setReferralInputs(profile.referral_code || "");

    const rewardRate = Number(profile.reward_rate_percent || 20);
    const friendDiscount = Number(profile.friend_discount_percent || 10);
    const affiliateMax = Number(profile.affiliate_max_percent || 60);
    const invites = Number(profile.total_invites || 0);
    const verified = Number(profile.verified_referrals || 0);
    const rewards = Number(profile.total_rewards_usdt || 0);

    if (referRewardRate) referRewardRate.textContent = `${rewardRate}%`;
    if (referFriendDiscount) referFriendDiscount.textContent = `${friendDiscount}%`;
    if (referAffiliateMax) referAffiliateMax.textContent = `${affiliateMax}%`;

    if (referralInviteCount) referralInviteCount.textContent = invites.toLocaleString("en-IN");
    if (referralVerifiedCount) referralVerifiedCount.textContent = verified.toLocaleString("en-IN");
    if (referralRewardTotal) referralRewardTotal.textContent = formatUsdt(rewards);

    if (referralProgressBar) {
        const progress = invites > 0 ? Math.min(100, Math.round((verified / invites) * 100)) : 0;
        referralProgressBar.style.width = `${progress}%`;
    }

    if (referralStatusBadge) {
        referralStatusBadge.textContent = profile.status === "active" ? "Active" : "Inactive";
        referralStatusBadge.className = profile.status === "active"
            ? "rounded-full bg-emerald-400/10 px-3 py-1 text-xs font-black text-emerald-400"
            : "rounded-full bg-red-400/10 px-3 py-1 text-xs font-black text-red-300";
    }

    if (commissionInput && rewardRate > 0) {
        commissionInput.value = String(Math.min(rewardRate, 60));
    }

    if (refreshReferralBtn) {
        const currencyLabel = (policy.currency === "USDT") ? "USD" : (policy.currency || "");
        refreshReferralBtn.textContent = `Refresh Referral Data${currencyLabel ? ` (${currencyLabel})` : ""}`;
    }

    calculateRewards();
}

async function loadReferralDashboard(showSuccessMessage = false) {
    if (!isLoggedIn()) {
        setLoginRequiredState();
        return;
    }

    try {
        if (refreshReferralBtn) {
            refreshReferralBtn.disabled = true;
            refreshReferralBtn.textContent = "Loading referral data...";
        }

        const response = await apiRequest("/referral/me");
        updateReferralUi(response.data || {});

        if (showSuccessMessage) {
            showMiniMessage("Referral data refreshed from backend.", "success");
        }
    } catch (error) {
        setLoginRequiredState();
        showMiniMessage(showApiError(error, "Referral data could not be loaded."), "error");
    } finally {
        if (refreshReferralBtn) {
            refreshReferralBtn.disabled = false;
        }
    }
}

async function copyText(text, successMessage) {
    const cleanText = String(text || "").trim();

    if (!cleanText || cleanText === "LOGIN REQUIRED" || cleanText.startsWith("Login to")) {
        showMiniMessage("Login first to get your referral code.", "error");
        return;
    }

    try {
        await navigator.clipboard.writeText(cleanText);
        showMiniMessage(successMessage, "success");
    } catch (error) {
        console.error(error);
        showMiniMessage("Copy failed. Please copy manually.", "error");
    }
}

function shareReferral(platform) {
    if (!referralLinkInput || !referralState) {
        showMiniMessage("Login first to share your referral link.", "error");
        return;
    }

    const link = referralLinkInput.value;
    const message = `Join TraidiumX using my referral link and start crypto futures/options trading: ${link}`;

    if (platform === "whatsapp") {
        window.open(`https://wa.me/?text=${encodeURIComponent(message)}`, "_blank");
        return;
    }

    if (platform === "telegram") {
        window.open(`https://t.me/share/url?url=${encodeURIComponent(link)}&text=${encodeURIComponent("Join TraidiumX using my referral link")}`, "_blank");
        return;
    }

    if (navigator.share) {
        navigator.share({
            title: "Join TraidiumX",
            text: "Join TraidiumX using my referral link",
            url: link
        }).catch(() => {
            showMiniMessage("Share cancelled.", "error");
        });
    } else {
        copyText(link, "Referral link copied. Share it anywhere.");
    }
}

function calculateRewards() {
    const friends = Math.max(0, Number(activeFriendsInput ? activeFriendsInput.value : 0));
    const avgFees = Math.max(0, Number(avgFeeInput ? avgFeeInput.value : 0));
    let commission = Math.max(0, Number(commissionInput ? commissionInput.value : 0));

    if (commission > 60) {
        commission = 60;
        if (commissionInput) {
            commissionInput.value = "60";
        }
    }

    const monthlyReward = friends * avgFees * (commission / 100);
    const dailyEstimate = monthlyReward / 30;
    const yearlyEstimate = monthlyReward * 12;

    if (estimatedReward) {
        estimatedReward.textContent = formatUsdt(monthlyReward);
    }

    if (rewardBreakdown) {
        rewardBreakdown.textContent = `${friends} friends × ${formatUsdt(avgFees)} fees × ${commission}% commission`;
    }

    if (dailyReward) {
        dailyReward.textContent = formatUsdt(dailyEstimate);
    }

    if (yearlyReward) {
        yearlyReward.textContent = formatUsdt(yearlyEstimate);
    }

    if (ratePreview) {
        ratePreview.textContent = `${commission}%`;
    }
}

function validateEmail(email) {
    return /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email);
}

async function handleAffiliateSubmit(event) {
    event.preventDefault();

    if (!isLoggedIn()) {
        showMiniMessage("Login first to apply for affiliate program.", "error");
        return;
    }

    const name = affiliateName ? affiliateName.value.trim() : "";
    const email = affiliateEmail ? affiliateEmail.value.trim() : "";
    const audience = affiliateAudience ? affiliateAudience.value.trim() : "";
    const platform = affiliatePlatform ? affiliatePlatform.value.trim() : "";
    const submitButton = affiliateForm ? affiliateForm.querySelector("button[type='submit']") : null;

    if (name.length < 2) {
        showMiniMessage("Please enter a valid full name.", "error");
        return;
    }

    if (!validateEmail(email)) {
        showMiniMessage("Please enter a valid email address.", "error");
        return;
    }

    if (!audience) {
        showMiniMessage("Please select your community size.", "error");
        return;
    }

    if (platform.length < 2) {
        showMiniMessage("Please enter your main platform.", "error");
        return;
    }

    try {
        if (submitButton) {
            submitButton.disabled = true;
            submitButton.dataset.originalText = submitButton.textContent;
            submitButton.textContent = "Submitting...";
        }

        const response = await apiRequest("/referral/affiliate/apply", {
            method: "POST",
            body: JSON.stringify({
                name,
                email,
                audience,
                platform
            })
        });

        if (affiliateFormMessage) {
            affiliateFormMessage.classList.remove("hidden");
            affiliateFormMessage.textContent = response.message || "Affiliate application submitted successfully.";
        }

        showMiniMessage("Affiliate application submitted successfully.", "success");

        window.setTimeout(() => {
            affiliateForm.reset();
        }, 1200);
    } catch (error) {
        const message = showApiError(error, "Affiliate application failed.");

        if (affiliateFormMessage) {
            affiliateFormMessage.classList.remove("hidden");
            affiliateFormMessage.textContent = message;
        }

        showMiniMessage(message, "error");
    } finally {
        if (submitButton) {
            submitButton.disabled = false;
            submitButton.textContent = submitButton.dataset.originalText || "Apply For Affiliate Program";
        }
    }
}

function initReferralEvents() {
    if (copyCodeBtn && referralCodeInput) {
        copyCodeBtn.addEventListener("click", () => {
            copyText(referralCodeInput.value, "Referral code copied.");
        });
    }

    if (copyReferralBtn && referralLinkInput) {
        copyReferralBtn.addEventListener("click", () => {
            copyText(referralLinkInput.value, "Referral link copied.");
        });
    }

    if (refreshReferralBtn) {
        refreshReferralBtn.addEventListener("click", () => loadReferralDashboard(true));
    }

    if (shareWhatsappBtn) {
        shareWhatsappBtn.addEventListener("click", () => shareReferral("whatsapp"));
    }

    if (shareTelegramBtn) {
        shareTelegramBtn.addEventListener("click", () => shareReferral("telegram"));
    }

    if (shareNativeBtn) {
        shareNativeBtn.addEventListener("click", () => shareReferral("native"));
    }
}

function initCalculatorEvents() {
    [activeFriendsInput, avgFeeInput, commissionInput].forEach((input) => {
        if (input) {
            input.addEventListener("input", calculateRewards);
        }
    });
}

function initAffiliateForm() {
    if (affiliateForm) {
        affiliateForm.addEventListener("submit", handleAffiliateSubmit);
    }
}

function initReferPage() {
    setLoginRequiredState();
    calculateRewards();
    initReferralEvents();
    initCalculatorEvents();
    initAffiliateForm();
    loadReferralDashboard(false);
}

document.addEventListener("DOMContentLoaded", initReferPage);
